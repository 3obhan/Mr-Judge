import React from 'react';
import { toLocaleDigits, formatReportDateTime, truncateForOnePage } from '@/lib/pdf-report';

// A4 width in CSS pixels at 96dpi - also just happens to be a comfortable
// reading width, and matches the @page { size: A4 } rule in index.css.
const REPORT_WIDTH = 794;

// Kept deliberately compact (see the spacing scale used below) and paired
// with truncateForOnePage() on the statements, since a long statement is
// the one part of this report with no length limit of its own - everything
// else (scores, verdict, explanation) is already short by design (see the
// prompt in api/analyze.js), so this is the one place that needs an
// explicit cap to guarantee the whole report always fits on a single page.
const STATEMENT_CHAR_LIMIT = 420;

/**
 * VerdictReport
 * A formal, print-only, single-page layout: letterhead, both parties'
 * statements, scores, verdict, reasoning, and an official-style seal with
 * date/time in the footer. Hidden on screen and shown only via the
 * browser's print dialog (see VerdictDisplay's "Download PDF" button) -
 * never shown directly in the interactive UI.
 */
export default function VerdictReport({ result, personA_statement, personB_statement, language = 'en' }) {
  const isRTL = language === 'fa';

  const t = isRTL
    ? {
        title: 'گزارش داوری اختلاف',
        subtitle: 'Mr Judge — سامانه‌ی داوری هوشمند',
        date: 'تاریخ و ساعت صدور',
        personA: 'بیانیه‌ی شخص الف',
        personB: 'بیانیه‌ی شخص ب',
        scoreA: 'امتیاز شخص الف',
        scoreB: 'امتیاز شخص ب',
        outOf: 'از ۱۰۰',
        verdict: 'حکم نهایی',
        explanation: 'تحلیل و استدلال',
        footer: 'این گزارش توسط هوش مصنوعی Mr Judge تهیه شده و صرفاً جنبه‌ی مشورتی دارد، نه حکمی الزام‌آور.',
        sealTop: 'تأیید شده',
        sealBottom: 'هوش مصنوعی'
      }
    : {
        title: 'Dispute Verdict Report',
        subtitle: 'Mr Judge — AI Arbitration System',
        date: 'Date & Time Issued',
        personA: "Person A's Statement",
        personB: "Person B's Statement",
        scoreA: 'Person A Score',
        scoreB: 'Person B Score',
        outOf: '/ 100',
        verdict: 'Final Verdict',
        explanation: 'Analysis & Reasoning',
        footer: 'This report was generated by Mr Judge AI and is advisory only, not a binding ruling.',
        sealTop: 'VERIFIED',
        sealBottom: 'AI VERDICT'
      };

  const issuedAt = formatReportDateTime(new Date(), language);
  const statementA = truncateForOnePage(personA_statement, language, STATEMENT_CHAR_LIMIT);
  const statementB = truncateForOnePage(personB_statement, language, STATEMENT_CHAR_LIMIT);

  // Letter-spacing breaks the cursive joining between Persian/Arabic letters
  // (each one needs to sit flush against its neighbor to take the right
  // joined form) - only apply uppercase+tracking for Latin-script (English).
  const trackingClass = isRTL ? '' : 'uppercase tracking-wider';
  const trackingClassWide = isRTL ? '' : 'tracking-widest';

  return (
    <div
      dir={isRTL ? 'rtl' : 'ltr'}
      style={{ width: `${REPORT_WIDTH}px`, fontFamily: "'Vazirmatn', sans-serif" }}
      className="bg-white text-slate-900 p-10"
    >
      {/* Letterhead */}
      <div className="flex items-center justify-between border-b-2 border-slate-800 pb-4 mb-5">
        <div>
          <h1 className="text-xl font-bold text-slate-900">{t.title}</h1>
          <p className="text-xs text-slate-500 mt-0.5">{t.subtitle}</p>
        </div>
        <img src="/mrjudge-logo.png" alt="" width={44} height={44} className="rounded-lg" />
      </div>

      {/* Both statements, side by side */}
      <div className="grid grid-cols-2 gap-5 mb-5">
        <div className="border border-slate-200 rounded-lg p-4">
          <h3 className={`text-[11px] font-semibold text-slate-500 mb-2 ${trackingClass}`}>
            {t.personA}
          </h3>
          <p className="text-[13px] leading-relaxed text-slate-800 whitespace-pre-wrap">
            {statementA}
          </p>
        </div>
        <div className="border border-slate-200 rounded-lg p-4">
          <h3 className={`text-[11px] font-semibold text-slate-500 mb-2 ${trackingClass}`}>
            {t.personB}
          </h3>
          <p className="text-[13px] leading-relaxed text-slate-800 whitespace-pre-wrap">
            {statementB}
          </p>
        </div>
      </div>

      {/* Scores */}
      <div className="grid grid-cols-2 gap-5 mb-5">
        <div className="text-center bg-slate-50 border border-slate-200 rounded-lg py-3">
          <div className={`text-[11px] text-slate-500 mb-0.5 ${trackingClass}`}>{t.scoreA}</div>
          <div className="text-2xl font-bold text-slate-900">
            {toLocaleDigits(result.personA_score, language)}
            <span className="text-sm font-normal text-slate-400"> {t.outOf}</span>
          </div>
        </div>
        <div className="text-center bg-slate-50 border border-slate-200 rounded-lg py-3">
          <div className={`text-[11px] text-slate-500 mb-0.5 ${trackingClass}`}>{t.scoreB}</div>
          <div className="text-2xl font-bold text-slate-900">
            {toLocaleDigits(result.personB_score, language)}
            <span className="text-sm font-normal text-slate-400"> {t.outOf}</span>
          </div>
        </div>
      </div>

      {/* Verdict */}
      <div className="bg-amber-50 border-2 border-amber-200 rounded-lg p-4 mb-5">
        <h3 className={`text-[11px] font-semibold text-amber-700 mb-1.5 ${trackingClass}`}>
          {t.verdict}
        </h3>
        <p className="text-[15px] font-medium text-slate-900 leading-relaxed">{result.verdict}</p>
      </div>

      {/* Explanation */}
      <div className="mb-6">
        <h3 className={`text-[11px] font-semibold text-slate-500 mb-1.5 ${trackingClass}`}>
          {t.explanation}
        </h3>
        <p className="text-[13px] leading-relaxed text-slate-700">{result.explanation}</p>
      </div>

      {/* Footer: disclaimer + official-style seal with date/time */}
      <div className="border-t border-slate-200 pt-4 flex items-center justify-between">
        <p className="text-[9px] text-slate-400 max-w-[58%] leading-relaxed">{t.footer}</p>

        <div className="flex flex-col items-center shrink-0" style={{ transform: 'rotate(-6deg)' }}>
          <div className="w-[72px] h-[72px] rounded-full border-[3px] border-double p-1" style={{ borderColor: '#9f1d1d' }}>
            <div
              className="w-full h-full rounded-full border flex flex-col items-center justify-center gap-0.5"
              style={{ borderColor: '#9f1d1d' }}
            >
              <span className={`text-[6.5px] font-bold ${trackingClassWide}`} style={{ color: '#9f1d1d' }}>
                {t.sealTop}
              </span>
              <img src="/mrjudge-logo.png" alt="" className="w-6 h-6 object-contain" />
              <span className={`text-[6px] font-bold ${trackingClassWide}`} style={{ color: '#9f1d1d' }}>
                {t.sealBottom}
              </span>
            </div>
          </div>
        </div>
      </div>
      <p dir="ltr" className="text-[9px] text-slate-400 text-center mt-2">
        {t.date}: <span className="font-medium text-slate-600">{issuedAt}</span>
      </p>
    </div>
  );
}
